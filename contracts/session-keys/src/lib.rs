//! Andromeda — Session Keys policy template.
//!
//! Lets the dWallet owner delegate signing authority to a temporary keypair
//! ("session key") under hard on-chain constraints:
//!   - expires_at_slot — automatic cutoff
//!   - max_uses        — total signatures the session can authorize
//!   - allowed_program_ids — caller (parsed_destination) whitelist
//!   - max_amount_per_tx   — per-tx amount cap
//!
//! Custody-free: Andromeda never holds the session keypair — the dev's app
//! generates and stores it client-side; this program registers the pubkey
//! and constraints on-chain so the Ika dWallet only signs when the session
//! keypair signs *first*.
//!
//! v2 (2026-05-07): owner is now wallet-agnostic and gas-sponsored. All
//! admin actions (`create_session`, `revoke_session`, `add_allowed_program`,
//! `remove_allowed_program`, `close_session`) authorize the owner via a
//! 32-byte off-chain challenge validated by `andromeda_auth`. The session
//! keypair still signs `request_signature_via_session` natively as a Solana
//! signer — that's the whole point of session keys.

#![no_std]
#![allow(dead_code)]

