// Every renderer takes:
//   * a pre-allocated 512-byte buffer (no heap),
//   * the typed parameters of the operation,
// and returns the byte length of the rendered ASCII message.
//
// The output is plain ASCII (`0x20..=0x7E`), valid UTF-8, and matches the
// spec in `docs/SPEC_CLEAR_SIGNING_FROZEN.md` byte-for-byte. Any edit here
// must also update the TS/Go mirrors and regenerate the golden vectors.
//
// Naming: each function mirrors the corresponding `*_challenge` in
// `challenge.rs` (or in `contracts/*/src/challenges.rs` for Phase 2).

// ── Phase 1: rules-policy recovery (3) ───────────────────────────

pub fn primary_recover_message(
    out: &mut [u8; MAX_HUMAN_MESSAGE_BYTES],
    dwallet: &Address,
    message_digest: &[u8; 32],
    metadata_digest: &[u8; 32],
    user_pubkey: &[u8; 32],
    signature_scheme: u16,
) -> Result<usize, HumanMessageError> {
    let mut w = MsgWriter::new(out);
    w.write_str("Recover dWallet ")?;
    w.write_base58_32(dwallet.as_array())?;
    w.write_str(" for message ")?;
    w.write_hex_lower(message_digest)?;
    w.write_str(" metadata ")?;
    w.write_hex_lower(metadata_digest)?;
    w.write_str(" scheme ")?;
    w.write_u16_dec(signature_scheme)?;
    w.write_str(" user ")?;
    w.write_hex_lower(user_pubkey)?;
    Ok(w.len())
}

